# SET UP #######################################################################

## Load packages ---------------------------------------------------------------
library(here)
library(tidyverse)
library(sf)

## Load data -------------------------------------------------------------------
turfs <- read_sf(here("data/processed/mex_turfs.gpkg"))
mex <- rnaturalearth::ne_countries(country = "Mexico")

# VISUALIZE ####################################################################

## Another step ----------------------------------------------------------------
p <- ggplot() +
  geom_sf(data = mex, fill = "gray25") +
  geom_sf(data = turfs, fill = "steelblue") +
  theme_linedraw()

# EXPORT #######################################################################


## The final step --------------------------------------------------------------  
ggsave(plot = p,
       filename = here("map.png"))
